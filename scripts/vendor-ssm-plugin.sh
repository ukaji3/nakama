#!/usr/bin/env bash
# vendor-ssm-plugin.sh
#
# Re-imports the AWS Session Manager plugin source into third_party/ so
# that `nakama aws connect` can drive Session Manager from a single Go
# binary (see docs/adr/0005-aws-connect-via-session-manager.md, 案3).
#
# The upstream repo (github.com/aws/session-manager-plugin) is NOT a
# published Go module (no go.mod; GOPATH-style vendor/). We therefore
# copy a pinned tag's source into the repo and resolve dependencies via
# hand-maintained go.mod files + `replace` directives in the root go.mod.
#
# Usage:
#   scripts/vendor-ssm-plugin.sh            # import the latest stable release
#   scripts/vendor-ssm-plugin.sh 1.2.814.0  # import a specific tag
#
# After running, review the diff, run `go mod tidy && go build ./...`,
# and update third_party/session-manager-plugin/PINNED.md if the tag
# changed.

set -euo pipefail

REPO="https://github.com/aws/session-manager-plugin.git"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="${ROOT}/third_party/session-manager-plugin"
UUID_DEST="${ROOT}/third_party/twinj-uuid"

# Packages under src/ that are command entrypoints, the test-only
# ssmcli, generated mocks, or test helpers; not needed when driving the
# session as a library (and they would pull in testify).
EXCLUDE_DIRS=(
  "sessionmanagerplugin-main"
  "ssmcli-main"
  "ssmclicommands"
)

# Individual files to drop after copy (test helpers importing testify).
EXCLUDE_FILES=(
  "log/test_log.go"
)

resolve_latest_tag() {
  curl -fsSL "https://api.github.com/repos/aws/session-manager-plugin/releases/latest" \
    | grep -E '"tag_name"' | head -1 | sed -E 's/.*"tag_name": *"([^"]+)".*/\1/'
}

TAG="${1:-$(resolve_latest_tag)}"
if [[ -z "${TAG}" ]]; then
  echo "error: could not resolve a release tag" >&2
  exit 1
fi

WORK="$(mktemp -d)"
trap 'rm -rf "${WORK}"' EXIT

echo ">> cloning session-manager-plugin @ ${TAG}"
git clone --depth 1 --branch "${TAG}" "${REPO}" "${WORK}/smp" >/dev/null 2>&1
COMMIT="$(git -C "${WORK}/smp" rev-parse HEAD)"
echo ">> tag=${TAG} commit=${COMMIT}"

# --- session-manager-plugin src/ ---------------------------------------
echo ">> copying src/ (excluding command/test files)"
rm -rf "${DEST}/src"
mkdir -p "${DEST}/src"
# Build an rsync-style exclusion for cp via find.
EXCLUDE_FIND=()
for d in "${EXCLUDE_DIRS[@]}"; do
  EXCLUDE_FIND+=(-path "${WORK}/smp/src/${d}" -prune -o)
done
# Copy every .go file except *_test.go and the excluded dirs, preserving layout.
find "${WORK}/smp/src" "${EXCLUDE_FIND[@]}" -name '*.go' ! -name '*_test.go' -type f -print \
  | while read -r f; do
      rel="${f#"${WORK}/smp/src/"}"
      mkdir -p "${DEST}/src/$(dirname "${rel}")"
      cp "${f}" "${DEST}/src/${rel}"
    done

# Drop generated mock packages (import testify/mock, unused as a library).
find "${DEST}/src" -type d -name 'mocks' -exec rm -rf {} + 2>/dev/null || true
# Drop test helper files (test_*.go: not _test.go but import testify/mocks).
find "${DEST}/src" -type f -name 'test_*.go' -delete
# Drop individually excluded files.
for rel in "${EXCLUDE_FILES[@]}"; do
  rm -f "${DEST}/src/${rel}"
done

cp "${WORK}/smp/LICENSE" "${DEST}/LICENSE"
cp "${WORK}/smp/NOTICE" "${DEST}/NOTICE"
cp "${WORK}/smp/THIRD-PARTY" "${DEST}/THIRD-PARTY" 2>/dev/null || true
cp "${WORK}/smp/VERSION" "${DEST}/VERSION"

# go.mod for the vendored plugin module. Dependency versions are pinned
# to match the nakama root module (aws-sdk-go-v2 v1.32.x) so MVS does not
# force an SDK upgrade. Adjust here if a future snapshot needs new deps.
cat > "${DEST}/go.mod" <<'EOF'
// Vendored snapshot of github.com/aws/session-manager-plugin (Apache-2.0).
// Generated by scripts/vendor-ssm-plugin.sh; see PINNED.md for the
// upstream tag/commit. Dependency versions are pinned to match the
// nakama root module; twinj/uuid is replaced in the root go.mod because
// no published version is API-compatible with this snapshot.
module github.com/aws/session-manager-plugin

go 1.23

require (
	github.com/aws/aws-sdk-go-v2 v1.32.7
	github.com/aws/aws-sdk-go-v2/service/kms v1.37.8
	github.com/aws/aws-sdk-go-v2/service/ssm v1.56.0
	github.com/aws/smithy-go v1.22.1
	github.com/cihub/seelog v0.0.0-20170130134532-f561c5e57575
	github.com/fsnotify/fsnotify v1.10.1
	github.com/gorilla/websocket v1.5.3
	github.com/twinj/uuid v1.0.0
	github.com/xtaci/smux v1.5.34
	golang.org/x/crypto v0.31.0
	golang.org/x/sync v0.10.0
	golang.org/x/sys v0.28.0
)
EOF

# --- twinj/uuid (no API-compatible published version exists) -----------
echo ">> copying vendored twinj/uuid (pinned, replaced in root go.mod)"
rm -rf "${UUID_DEST}"
mkdir -p "${UUID_DEST}"
find "${WORK}/smp/vendor/src/github.com/twinj/uuid" -maxdepth 1 -name '*.go' ! -name '*_test.go' -type f \
  -exec cp {} "${UUID_DEST}/" \;
cp "${WORK}/smp/vendor/src/github.com/twinj/uuid/LICENSE" "${UUID_DEST}/LICENSE" 2>/dev/null || true
cat > "${UUID_DEST}/go.mod" <<'EOF'
// Vendored snapshot of github.com/twinj/uuid as shipped in
// session-manager-plugin's GOPATH vendor tree. Pinned via a replace
// directive in the nakama root go.mod because the published twinj/uuid
// versions are not API-compatible with this snapshot.
module github.com/twinj/uuid

go 1.23
EOF

# --- provenance --------------------------------------------------------
cat > "${DEST}/PINNED.md" <<EOF
# Vendored session-manager-plugin

- Upstream: ${REPO}
- Tag: \`${TAG}\`
- Commit: \`${COMMIT}\`
- Imported by: \`scripts/vendor-ssm-plugin.sh\`
- License: Apache-2.0 (see LICENSE / NOTICE)

Driven as a library by \`internal/service/connect.go\`. Resolved as a Go
module via a hand-maintained \`go.mod\` + \`replace\` directives in the repo
root \`go.mod\`. \`twinj/uuid\` is vendored under \`third_party/twinj-uuid\`
because its published versions are not API-compatible with this snapshot.

To update: run \`scripts/vendor-ssm-plugin.sh [tag]\`, then
\`go mod tidy && go build ./...\`, and adjust go.mod requires if deps changed.
EOF

echo ">> done. tag=${TAG} commit=${COMMIT}"
echo ">> next: go mod tidy && go build ./... ; review diff"
