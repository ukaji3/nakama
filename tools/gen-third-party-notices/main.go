// Command gen-third-party-notices regenerates the THIRD-PARTY-NOTICES
// file from the Go module build graphs of ./cmd/nakama.
//
// Scope: the union of the module dependencies across all six release
// targets (linux, darwin, windows x amd64, arm64), plus the Go
// standard library and runtime that every Go binary statically links.
// License texts are read verbatim from each module's directory in the
// module cache (or third_party/ for vendored replacements) and grouped
// by exact content, so byte-identical texts (e.g. the generic
// Apache-2.0 text shared by the aws-sdk-go-v2 modules) appear once
// with the full module list. NOTICE files are reproduced as
// Apache-2.0 section 4(d) requires.
//
// The output is deterministic for a given dependency set and Go
// toolchain: no timestamps, tags, or environment-specific values are
// embedded. CI regenerates the file with -check and fails when the
// committed copy is stale.
//
// Usage:
//
//	go run ./tools/gen-third-party-notices           # rewrite THIRD-PARTY-NOTICES
//	go run ./tools/gen-third-party-notices -check    # verify freshness (CI)
//
// The command must run from the repository root.
package main

import (
	"crypto/sha256"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const (
	// mainPackage is the distributed binary whose build graph defines
	// which third-party components require notices.
	mainPackage = "./cmd/nakama"

	// defaultOutput is the notices file at the repository root.
	defaultOutput = "THIRD-PARTY-NOTICES"
)

// separator visually delimits the per-license sections.
var separator = strings.Repeat("=", 78)

// header is the fixed preamble of the generated file. It must stay
// free of environment-specific values (versions, dates, tags) so that
// regeneration is reproducible across machines and CI.
const header = `THIRD-PARTY NOTICES for nakama

nakama itself is proprietary software (All Rights Reserved; see README.md).
The distributed nakama binaries incorporate the third-party components
listed below. Each component is used under its own license, reproduced in
full in this file, together with the NOTICE files that some components
require to be redistributed.

Scope: union of the Go module build graphs of ./cmd/nakama for all release
targets (linux, darwin, windows x amd64, arm64), plus the Go standard
library and runtime that are statically linked into every Go binary.
Module versions are listed for traceability. This file is generated by
tools/gen-third-party-notices ("make notices") and its freshness is
enforced in CI; regenerate it whenever dependencies change.
`

// targets are the release build targets whose dependency graphs are
// unioned. Keep in sync with .goreleaser.yaml.
var targets = [][2]string{
	{"linux", "amd64"},
	{"linux", "arm64"},
	{"darwin", "amd64"},
	{"darwin", "arm64"},
	{"windows", "amd64"},
	{"windows", "arm64"},
}

// moduleInfo identifies one module in the build graph together with
// the on-disk directory its license files are read from.
type moduleInfo struct {
	Path    string // module path, e.g. github.com/aws/smithy-go
	Version string // module version as reported by go list
	Dir     string // module cache dir (or third_party/ replacement)
}

func main() {
	check := flag.Bool("check", false, "verify the committed file is up to date instead of writing it")
	out := flag.String("o", defaultOutput, "output file path")
	flag.Parse()
	if err := run(*check, *out); err != nil {
		fmt.Fprintln(os.Stderr, "gen-third-party-notices:", err)
		os.Exit(1)
	}
}

func run(check bool, outPath string) error {
	if _, err := os.Stat("go.mod"); err != nil {
		return fmt.Errorf("go.mod not found; run from the repository root: %w", err)
	}
	mods, err := collectModules()
	if err != nil {
		return err
	}
	stdlibLicense, err := readStdlibLicense()
	if err != nil {
		return err
	}
	content, err := buildNotices(stdlibLicense, mods)
	if err != nil {
		return err
	}
	if check {
		existing, err := os.ReadFile(outPath) // #nosec G304 -- path is the repo-local notices file (flag-provided in CI/Makefile)
		if err != nil {
			return fmt.Errorf("read %s: %w", outPath, err)
		}
		if string(existing) != content {
			reportDrift(string(existing), content)
			return fmt.Errorf("%s is stale; run `make notices` and commit the result", outPath)
		}
		fmt.Printf("%s is up to date (%d modules)\n", outPath, len(mods))
		return nil
	}
	if err := os.WriteFile(outPath, []byte(content), 0o644); err != nil { // #nosec G306 -- public notices file, world-readable on purpose
		return err
	}
	fmt.Printf("wrote %s (%d modules)\n", outPath, len(mods))
	return nil
}

// collectModules unions the non-stdlib, non-main module dependencies
// of mainPackage across all release targets.
func collectModules() ([]moduleInfo, error) {
	const format = `{{if and .Module (not .Standard)}}{{if not .Module.Main}}{{.Module.Path}}|{{.Module.Version}}|{{.Module.Dir}}{{end}}{{end}}`
	byPath := map[string]moduleInfo{}
	for _, t := range targets {
		cmd := exec.Command("go", "list", "-deps", "-f", format, mainPackage)
		cmd.Env = append(os.Environ(), "GOOS="+t[0], "GOARCH="+t[1])
		outBytes, err := cmd.Output()
		if err != nil {
			var ee *exec.ExitError
			if errors.As(err, &ee) {
				return nil, fmt.Errorf("go list (%s/%s): %w\n%s", t[0], t[1], err, ee.Stderr)
			}
			return nil, fmt.Errorf("go list (%s/%s): %w", t[0], t[1], err)
		}
		for _, line := range strings.Split(string(outBytes), "\n") {
			line = strings.TrimSpace(line)
			if line == "" {
				continue
			}
			parts := strings.SplitN(line, "|", 3)
			if len(parts) != 3 || parts[2] == "" {
				return nil, fmt.Errorf("go list (%s/%s): unexpected line %q (module not downloaded?)", t[0], t[1], line)
			}
			m := moduleInfo{Path: parts[0], Version: parts[1], Dir: parts[2]}
			if prev, ok := byPath[m.Path]; ok && prev.Version != m.Version {
				return nil, fmt.Errorf("module %s has conflicting versions across targets: %s vs %s", m.Path, prev.Version, m.Version)
			}
			byPath[m.Path] = m
		}
	}
	mods := make([]moduleInfo, 0, len(byPath))
	for _, m := range byPath {
		mods = append(mods, m)
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].Path < mods[j].Path })
	return mods, nil
}

// readStdlibLicense returns the license text of the Go toolchain that
// produces the distributed binaries (BSD-3-Clause, The Go Authors).
func readStdlibLicense() (string, error) {
	out, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return "", fmt.Errorf("go env GOROOT: %w", err)
	}
	goroot := strings.TrimSpace(string(out))
	b, err := os.ReadFile(filepath.Join(goroot, "LICENSE")) // #nosec G304 -- fixed path under the trusted Go toolchain root
	if err != nil {
		return "", fmt.Errorf("read Go stdlib license: %w", err)
	}
	return string(b), nil
}

// noticeEntry is one NOTICE file to reproduce inside a license group.
type noticeEntry struct {
	ModulePath string
	Text       string
}

// licenseGroup collects the modules sharing one byte-identical license
// text.
type licenseGroup struct {
	Label   string // human-readable license name
	Text    string // verbatim license text
	Modules []moduleInfo
	Notices []noticeEntry
}

// buildNotices renders the full THIRD-PARTY-NOTICES document. It is a
// pure function of its inputs so tests can exercise it with fixtures.
func buildNotices(stdlibLicense string, mods []moduleInfo) (string, error) {
	groups := map[[32]byte]*licenseGroup{}
	for _, m := range mods {
		licPath, err := findFirstFile(m.Dir, "LICENSE", "COPYING")
		if err != nil {
			return "", fmt.Errorf("module %s: %w", m.Path, err)
		}
		licBytes, err := os.ReadFile(licPath) // #nosec G304 -- path discovered under the module cache directory
		if err != nil {
			return "", fmt.Errorf("module %s: read license: %w", m.Path, err)
		}
		label, err := classifyLicense(string(licBytes))
		if err != nil {
			return "", fmt.Errorf("module %s (%s): %w", m.Path, licPath, err)
		}
		// Normalize CRLF (e.g. seelog's license file) so the document
		// uses one line-ending style throughout; the text itself stays
		// verbatim.
		licText := strings.ReplaceAll(string(licBytes), "\r\n", "\n")
		key := sha256.Sum256([]byte(licText))
		g, ok := groups[key]
		if !ok {
			g = &licenseGroup{Label: label, Text: licText}
			groups[key] = g
		}
		g.Modules = append(g.Modules, m)
		if noticePath, err := findFirstFile(m.Dir, "NOTICE"); err == nil {
			noticeBytes, err := os.ReadFile(noticePath) // #nosec G304 -- path discovered under the module cache directory
			if err != nil {
				return "", fmt.Errorf("module %s: read notice: %w", m.Path, err)
			}
			noticeText := strings.ReplaceAll(string(noticeBytes), "\r\n", "\n")
			g.Notices = append(g.Notices, noticeEntry{ModulePath: m.Path, Text: strings.TrimSpace(noticeText)})
		}
	}

	ordered := make([]*licenseGroup, 0, len(groups))
	for _, g := range groups {
		sort.Slice(g.Modules, func(i, j int) bool { return g.Modules[i].Path < g.Modules[j].Path })
		sort.Slice(g.Notices, func(i, j int) bool { return g.Notices[i].ModulePath < g.Notices[j].ModulePath })
		ordered = append(ordered, g)
	}
	sort.Slice(ordered, func(i, j int) bool { return ordered[i].Modules[0].Path < ordered[j].Modules[0].Path })

	var out []string
	out = append(out, header)

	// The Go toolchain itself comes first: it is linked into every
	// binary regardless of the module graph.
	out = appendSection(out,
		"Go standard library and runtime — BSD 3-Clause License",
		[]string{"  - Go standard library and runtime"},
		nil, stdlibLicense)

	for _, g := range ordered {
		title := fmt.Sprintf("%s — %s", g.Modules[0].Path, g.Label)
		if len(g.Modules) > 1 {
			title = fmt.Sprintf("%s and related modules (%d modules) — %s", g.Modules[0].Path, len(g.Modules), g.Label)
		}
		lines := make([]string, 0, len(g.Modules))
		for _, m := range g.Modules {
			lines = append(lines, fmt.Sprintf("  - %s %s", m.Path, m.Version))
		}
		out = appendSection(out, title, lines, g.Notices, g.Text)
	}
	return strings.Join(out, "\n") + "\n", nil
}

// appendSection renders one license section: separator, title, module
// list, reproduced NOTICE files, then the verbatim license text.
func appendSection(out []string, title string, moduleLines []string, notices []noticeEntry, licenseText string) []string {
	out = append(out, separator, title, "")
	out = append(out, moduleLines...)
	for _, n := range notices {
		out = append(out, "", fmt.Sprintf("NOTICE (%s):", n.ModulePath), "")
		for _, l := range strings.Split(n.Text, "\n") {
			if l == "" {
				out = append(out, "")
			} else {
				out = append(out, "    "+l)
			}
		}
	}
	out = append(out, "", strings.TrimRight(licenseText, "\n"), "")
	return out
}

// findFirstFile returns the lexicographically first direct child of
// dir whose name starts (case-insensitively) with one of the prefixes,
// trying each prefix in order.
func findFirstFile(dir string, prefixes ...string) (string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", fmt.Errorf("read dir %s: %w", dir, err)
	}
	for _, prefix := range prefixes {
		var names []string
		for _, e := range entries {
			if e.IsDir() {
				continue
			}
			if strings.HasPrefix(strings.ToUpper(e.Name()), prefix) {
				names = append(names, e.Name())
			}
		}
		if len(names) > 0 {
			sort.Strings(names)
			return filepath.Join(dir, names[0]), nil
		}
	}
	return "", fmt.Errorf("no %s file found in %s", strings.Join(prefixes, "/"), dir)
}

// classifyLicense maps a license text to a human-readable label. It
// intentionally fails on anything it does not recognize: a new license
// type entering the dependency graph must be reviewed by a human (and
// this classifier extended) rather than silently labeled.
func classifyLicense(text string) (string, error) {
	switch {
	case strings.Contains(text, "This project is covered by two different licenses: MIT and Apache"):
		// gopkg.in/yaml.v3 dual license.
		return "MIT License and Apache License 2.0", nil
	case strings.Contains(text, "Apache License") && strings.Contains(text, "Version 2.0"):
		// Full Apache-2.0 text or a short grant notice referencing it.
		return "Apache License 2.0", nil
	case strings.Contains(text, "Permission is hereby granted, free of charge"):
		return "MIT License", nil
	case strings.Contains(text, "Redistribution and use in source and binary forms"):
		// BSD family: distinguish by the presence of the optional
		// clauses. The 4th (advertising) clause would demand extra
		// obligations, so surface it distinctly if it ever appears.
		if strings.Contains(text, "advertising materials") {
			return "BSD 4-Clause License", nil
		}
		if strings.Contains(text, "endorse or promote") ||
			strings.Contains(text, "names of its contributors") ||
			strings.Contains(text, "neither the name") ||
			strings.Contains(text, "Neither the name") {
			return "BSD 3-Clause License", nil
		}
		return "BSD 2-Clause License", nil
	}
	return "", fmt.Errorf("unrecognized license text; extend classifyLicense in tools/gen-third-party-notices after reviewing the license")
}

// reportDrift prints a compact line-oriented summary of where the
// committed file and the regenerated content diverge.
func reportDrift(existing, generated string) {
	el := strings.Split(existing, "\n")
	gl := strings.Split(generated, "\n")
	n := len(el)
	if len(gl) < n {
		n = len(gl)
	}
	for i := 0; i < n; i++ {
		if el[i] != gl[i] {
			fmt.Fprintf(os.Stderr, "first difference at line %d:\n  committed: %q\n  generated: %q\n", i+1, el[i], gl[i])
			return
		}
	}
	fmt.Fprintf(os.Stderr, "files differ in length: committed %d lines, generated %d lines\n", len(el), len(gl))
}
