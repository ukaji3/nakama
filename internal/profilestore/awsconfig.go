package profilestore

import (
	"fmt"
	"sort"
	"strings"

	nakamaConfig "github.com/ukaji3/nakama/internal/config"
)

// renderAWSConfig renders the full aws_config content from the
// registry. The file is regenerated from scratch on every save (never
// patched in place) so it can never drift from profiles.json.
//
// Each saved account becomes one AWS-CLI-format profile section:
//
//	[profile nakama-<accountID>]
//	login_session = <identity-ARN-shaped identifier>
//	region = ap-northeast-1
//
// No secret material is ever written here: login_session is only a
// pointer into the AWS CLI's own token cache (~/.aws/login/cache/).
func renderAWSConfig(d *Data) string {
	profiles := make([]Profile, len(d.Profiles))
	copy(profiles, d.Profiles)
	sort.Slice(profiles, func(i, j int) bool {
		return profiles[i].AccountID < profiles[j].AccountID
	})

	var b strings.Builder
	b.WriteString("# Generated by nakama (`nakama aws profile save`). DO NOT EDIT.\n")
	b.WriteString("# This file is regenerated from profiles.json on every save.\n")
	b.WriteString("#\n")
	b.WriteString("# It contains NO secrets: login_session is a non-secret session\n")
	b.WriteString("# identifier; the actual tokens live in ~/.aws/login/cache/ and are\n")
	b.WriteString("# managed by the AWS CLI (refresh tokens expire after at most 12h).\n")
	for _, p := range profiles {
		b.WriteString("\n")
		fmt.Fprintf(&b, "[profile %s]\n", ProfileName(p.AccountID))
		fmt.Fprintf(&b, "login_session = %s\n", p.LoginSession)
		fmt.Fprintf(&b, "region = %s\n", nakamaConfig.Region)
	}
	return b.String()
}
